#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY_PATH = join(ROOT, 'docs/architecture/c-lua-ownership.json');
const OUTPUT_PATH = join(ROOT, 'docs/architecture/c-lua-ownership.generated.md');
const ALLOWED_STATUSES = new Set(['implemented', 'partial', 'stubbed', 'absent']);

function mermaidId(id) {
    return `n_${id.replace(/[^A-Za-z0-9_]/g, '_')}`;
}

export function loadAndValidateOwnershipRegistry() {
    const registry = JSON.parse(readFileSync(REGISTRY_PATH, 'utf8'));
    const failures = [];
    if (registry.schemaVersion !== 1) failures.push('schemaVersion must be 1');
    if (JSON.stringify(registry.statuses) !== JSON.stringify([...ALLOWED_STATUSES]))
        failures.push('statuses must be implemented, partial, stubbed, absent');
    if (!Array.isArray(registry.entries)) failures.push('entries must be an array');

    const ids = new Set();
    for (const entry of registry.entries || []) {
        if (!entry.id || ids.has(entry.id)) failures.push(`duplicate or missing id: ${entry.id}`);
        ids.add(entry.id);
        if (!ALLOWED_STATUSES.has(entry.status))
            failures.push(`${entry.id}: invalid status ${entry.status}`);
        for (const key of ['javascriptOwners', 'dependencies', 'bridgeIds', 'acceptanceWitnesses']) {
            if (!Array.isArray(entry[key])) failures.push(`${entry.id}: ${key} must be an array`);
        }
        for (const key of ['cFiles', 'cSymbols', 'luaFiles', 'luaSymbols']) {
            if (!Array.isArray(entry.source?.[key]))
                failures.push(`${entry.id}: source.${key} must be an array`);
        }
        if (typeof entry.openGap !== 'string' || !entry.openGap.trim())
            failures.push(`${entry.id}: openGap must be explicit`);
        if (entry.lastSealedGate !== null && typeof entry.lastSealedGate !== 'string')
            failures.push(`${entry.id}: lastSealedGate must be null or a string`);
        const componentIds = new Set();
        if (entry.components != null && !Array.isArray(entry.components))
            failures.push(`${entry.id}: components must be an array when present`);
        for (const component of entry.components || []) {
            if (!component.id || componentIds.has(component.id))
                failures.push(`${entry.id}: duplicate or missing component id: ${component.id}`);
            componentIds.add(component.id);
            if (!ALLOWED_STATUSES.has(component.status))
                failures.push(`${entry.id}/${component.id}: invalid status ${component.status}`);
            if (typeof component.openGap !== 'string' || !component.openGap.trim())
                failures.push(`${entry.id}/${component.id}: openGap must be explicit`);
        }
    }
    for (const entry of registry.entries || []) {
        for (const dependency of entry.dependencies || []) {
            if (!ids.has(dependency)) failures.push(`${entry.id}: unknown dependency ${dependency}`);
        }
    }
    if (failures.length) throw new Error(failures.join('\n'));
    return registry;
}

export function renderOwnershipMap(registry) {
    const counts = Object.fromEntries([...ALLOWED_STATUSES].map(status => [status, 0]));
    for (const entry of registry.entries) counts[entry.status]++;
    const lines = [
        '# Generated C/Lua ownership status',
        '',
        '<!-- Generated by scripts/generate-ownership-map.mjs; edit c-lua-ownership.json. -->',
        '',
        `Scope: ${registry.scope}.`,
        '',
        '| Implemented | Partial | Stubbed | Absent | Total |',
        '| ---: | ---: | ---: | ---: | ---: |',
        `| ${counts.implemented} | ${counts.partial} | ${counts.stubbed} | ${counts.absent} | ${registry.entries.length} |`,
        '',
        '```mermaid',
        'flowchart LR',
    ];
    for (const entry of registry.entries) {
        lines.push(`    ${mermaidId(entry.id)}["${entry.label}<br/>${entry.status}"]`);
    }
    for (const entry of registry.entries) {
        for (const dependency of entry.dependencies)
            lines.push(`    ${mermaidId(entry.id)} --> ${mermaidId(dependency)}`);
    }
    lines.push('```', '', '| Subsystem | Status | JavaScript owner | Bridges | Open gap |',
        '| --- | --- | --- | --- | --- |');
    for (const entry of registry.entries) {
        lines.push(`| ${entry.label} | ${entry.status} | ${entry.javascriptOwners.join('<br/>') || 'none'} | ${entry.bridgeIds.join('<br/>') || 'none'} | ${entry.openGap} |`);
    }
    const componentEntries = registry.entries.flatMap(entry =>
        (entry.components || []).map(component => ({ entry, component })),
    );
    if (componentEntries.length) {
        lines.push('', '## Component ownership', '',
            '| Subsystem | Component | Status | Open gap |',
            '| --- | --- | --- | --- |');
        for (const { entry, component } of componentEntries) {
            lines.push(`| ${entry.label} | ${component.label || component.id} | ${component.status} | ${component.openGap} |`);
        }
    }
    lines.push('', 'No entry has a sealed-corpus gate yet. Public-session witnesses are retained only where the registry explicitly labels them as regressions.', '');
    return lines.join('\n');
}

const registry = loadAndValidateOwnershipRegistry();
const rendered = renderOwnershipMap(registry);
if (process.argv.includes('--check')) {
    const current = readFileSync(OUTPUT_PATH, 'utf8');
    if (current !== rendered) {
        console.error('Generated ownership map is stale. Run npm run ownership:generate.');
        process.exitCode = 1;
    }
} else {
    writeFileSync(OUTPUT_PATH, rendered);
    console.log(`wrote ${OUTPUT_PATH}`);
}
