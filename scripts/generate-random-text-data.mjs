#!/usr/bin/env node
// Generate browser-loadable source data for engrave.c random text.
// The source files remain authoritative; this module only removes the
// filesystem dependency from the JavaScript port.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

function sourceLines(relativePath) {
    const text = readFileSync(`${root}/${relativePath}`, 'utf8').replace(/\r\n/g, '\n');
    const lines = text.split('\n');
    if (lines.at(-1) === '') lines.pop();
    return lines;
}

const trueRumors = sourceLines('nethack-c/upstream/dat/rumors.tru');
const falseRumors = sourceLines('nethack-c/upstream/dat/rumors.fal');
const engravings = sourceLines('nethack-c/upstream/dat/engrave.txt')
    .filter(line => line && !line.startsWith('#') && !line.startsWith('^'));
engravings.unshift('No matter where you go, there you are.');
const epitaphs = sourceLines('nethack-c/upstream/dat/epitaph.txt')
    .filter(line => line && !line.startsWith('#'));
// makedefs guarantees a non-empty compiled file by prepending this fallback.
// It is part of the selectable padded text region, unlike the header record.
epitaphs.unshift('No matter where I went, here I am.');
// makedefs prepends the fallback "bogon", removes comments and blank lines,
// and pads each encrypted bogus-monster line to at least 19 characters plus
// its newline (MD_PAD_BOGONS is 20 including that newline).  Preserve the
// unencrypted lines and layout size so get_rnd_line() can be reproduced in a
// browser without loading NetHack's compiled data file.
const bogusMonsters = sourceLines('nethack-c/upstream/dat/bogusmon.txt')
    .filter(line => line && !line.startsWith('#'));
bogusMonsters.unshift('bogon');
const bogusMonsterFileSize = bogusMonsters.reduce(
    (size, line) => size + Math.max(19, line.length) + 1, 0,
);

const output = `// Generated by scripts/generate-random-text-data.mjs.\n`
    + `// Sources: nethack-c/upstream/dat/{rumors.tru,rumors.fal,engrave.txt,epitaph.txt,bogusmon.txt}.\n\n`
    + `export const TRUE_RUMORS = ${JSON.stringify(trueRumors)};\n`
    + `export const FALSE_RUMORS = ${JSON.stringify(falseRumors)};\n`
    + `export const RANDOM_ENGRAVINGS = ${JSON.stringify(engravings)};\n`
    + `export const RANDOM_EPITAPHS = ${JSON.stringify(epitaphs)};\n`
    + `export const BOGUS_MONSTERS = ${JSON.stringify(bogusMonsters)};\n`
    + `export const BOGUS_MONSTER_FILE_SIZE = ${bogusMonsterFileSize};\n`;

writeFileSync(`${root}/js/random_text_data.js`, output);
