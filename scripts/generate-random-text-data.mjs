#!/usr/bin/env node
// Generate browser-loadable source data for engrave.c random text.
// The source files remain authoritative; this module only removes the
// filesystem dependency from the JavaScript port.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

function sourceLines(relativePath) {
    const text = readFileSync(`${root}/${relativePath}`, 'utf8').replace(/\r\n/g, '\n');
    const lines = text.split('\n');
    if (lines.at(-1) === '') lines.pop();
    return lines;
}

const trueRumors = sourceLines('nethack-c/upstream/dat/rumors.tru');
const falseRumors = sourceLines('nethack-c/upstream/dat/rumors.fal');
const engravings = sourceLines('nethack-c/upstream/dat/engrave.txt')
    .filter(line => line && !line.startsWith('#') && !line.startsWith('^'));
engravings.unshift('No matter where you go, there you are.');

const output = `// Generated by scripts/generate-random-text-data.mjs.\n`
    + `// Sources: nethack-c/upstream/dat/{rumors.tru,rumors.fal,engrave.txt}.\n\n`
    + `export const TRUE_RUMORS = ${JSON.stringify(trueRumors)};\n`
    + `export const FALSE_RUMORS = ${JSON.stringify(falseRumors)};\n`
    + `export const RANDOM_ENGRAVINGS = ${JSON.stringify(engravings)};\n`;

writeFileSync(`${root}/js/random_text_data.js`, output);
