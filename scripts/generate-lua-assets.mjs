import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = path.join(root, 'nethack-c', 'upstream', 'dat');
const output = path.join(root, 'js', 'generated', 'lua_sources.js');
const names = [
    'nhlib.lua', 'nhcore.lua', 'dungeon.lua',
    'bigrm-1.lua', 'bigrm-2.lua', 'bigrm-3.lua',
    'bigrm-4.lua', 'bigrm-5.lua', 'bigrm-6.lua',
    'bigrm-7.lua', 'bigrm-8.lua', 'bigrm-9.lua',
    'bigrm-10.lua', 'bigrm-11.lua', 'bigrm-12.lua', 'bigrm-13.lua',
    'medusa-1.lua', 'medusa-2.lua', 'medusa-3.lua', 'medusa-4.lua',
    'fakewiz1.lua', 'fakewiz2.lua',
    'wizard1.lua', 'wizard2.lua', 'wizard3.lua',
    'asmodeus.lua', 'baalz.lua', 'orcus.lua',
];

const sources = Object.fromEntries(await Promise.all(names.map(async name => [
    name,
    await readFile(path.join(sourceDirectory, name), 'utf8'),
])));

const moduleSource = [
    '// Generated by scripts/generate-lua-assets.mjs from the pinned Lua files.',
    `export const LUA_SOURCES = Object.freeze(${JSON.stringify(sources, null, 2)});`,
    '',
].join('\n');

await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, moduleSource);
