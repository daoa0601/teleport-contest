def flag_spec(macro, owner, record, old, new, slow):
    return Spec(
        f'{macro}:tables', f'verification_{macro}', owner,
        [('species', INT), ('native_pointer_present', INT)],
        slow=slow, js_file=MONDATA, assumptions=PREDICATE_ASSUMPTIONS,
        require_counterexamples=True,
        partitions=species_partitions if macro == 'cantweararm' else None,
        configure=species_predicate_state,
        arguments=species_record_arguments if record else species_predicate_arguments,
        pre=lambda s: [s['species'] >= 0, s['native_pointer_present'] == 1],
        probes=[('null native pointer at species 0', lambda s: [
            s['species'] == 0, s['native_pointer_present'] == 0])],
        mutant_pre=lambda s: [s['species'] == {'is_armed': 43, 'could_twoweap': 174}.get(macro, 0)],
        mutants=[(MONDATA, old, new)],
    )


