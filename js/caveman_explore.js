    swap: `5 2 10`,
    ready: `100 100 100 100 100 100 100 100 100 1 2 5 5 20 8 16 5 5 8 5 5 100 100 100 100 100 100 100 100 1 100 2 3 5 12 12 12 70 200 20 82`,
